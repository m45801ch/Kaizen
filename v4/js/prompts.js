/* Prompt 建構：自動填表、正式措辭、照片視覺分析、簡報生成 */
export function buildPrompt(d){
  const label = {
    title:"改善主題（僅供參考）", before:"改善前現況描述（口語）", after:"改善後對策描述（口語）",
    benefit1:"第一項預期效益", benefit2:"第二項預期效益", benefit3:"第三項預期效益"
  };
  const parts = [];
  [["title","title"],["before","before"],["after","after"],["benefit1","benefits"],["benefit2","benefits"],["benefit3","benefits"]].forEach(()=>{});
  const rows = [
    ["title", d.title],
    ["before", d.before],
    ["after", d.after],
    ["benefit1", d.benefits[0]],
    ["benefit2", d.benefits[1]],
    ["benefit3", d.benefits[2]]
  ];
  rows.forEach(r=>parts.push("- "+label[r[0]]+"："+(r[1]||"（未填）")));
  return [
    "你是企業「改善提案」撰寫專家。請根據使用者提供的內容，先「分析問題點」再產出一份結構完整、措辭專業正式的改善提案。",
    "",
    "使用者提供的資料：",
    parts.join("\n"),
    "",
    "請產出 JSON 物件，欄位如下：",
    "{",
    '  "title": "以「動詞＋對象＋結果」為核心的簡潔標題，20 字內",',
    '  "before": "深入分析問題並改寫。拆成 3 個「標題：內容」列點，每行開頭加「●」，行與行之間用「\\n」分行。標題由 AI 依問題自行判斷（例如：具體現象／根本成因／潛在風險），每點含標題只寫一行、約 15–18 字內，寧短勿長，確保單行顯示不換行。整段含標籤與符號控制在 100 字內。",',
    '  "after": "針對問題點給對策並改寫。拆成 3 個「標題：內容」列點，每行開頭加「●」，行與行之間用「\\n」分行。標題由 AI 自行判斷（例如：具體對策／執行重點／預期效果），每點含標題只寫一行、約 15–18 字內，寧短勿長，確保單行顯示不換行。整段含標籤與符號控制在 100 字內。",',
    '  "benefit1": "第一項預期效益，只寫一行、12 字內",',
    '  "benefit2": "第二項預期效益，只寫一行、12 字內",',
    '  "benefit3": "第三項預期效益，只寫一行、12 字內"',
    '  "safetyLevel": "依改善前的風險程度判定：高／中／低，只回傳其中一個字"',
    "}",
    "",
    "注意事項：",
    "1. 必須使用台灣繁體中文，嚴禁出現任何簡體中文字形（例如：写→寫、车→車、机→機、对→對、来→來）。輸出前請逐字檢查。",
    "2. 改善前（before）與改善後（after）各拆成 3 個列點，標題由 AI 自行判斷，每點只寫一行（含標題約 15–18 字內），寧短勿長，確保單行顯示不換行，禁止全部寫成一大段。",
    "3. 每個列點的「標題」用全形冒號「：」與內容分開（例如：具體現象：樓梯無扶手）。",
    "4. 內容中的重點詞彙（如：滑倒、墜落、風險、危險、安全、效率、成本等）請用「**」包起來（例如：**滑倒**、**墜落**），前端會以紅色粗體強調顯示。",
    "5. 三項預期效益各 12 字內，分別涵蓋不同面向（如：安全、效率、成本）。",
    "5b. 請同時判定改善前的風險等級（safetyLevel），只回傳「高」「中」「低」其中一個字；若無法判定則回傳「中」。",
    "6. 改善前（before）與改善後（after）的總字數各控制在 100 字內（含標籤與符號），這是 AI 生成時的硬性上限，請嚴格遵守。",
    "7. 判斷改善主題與內容，一律以「改善前（before）」與「改善後（after）」的描述內容為主要依據；若「改善主題」欄位與內容不符，請以內容為準，不要被舊的主題名稱誤導。",
    "8. 若使用者已提供正式內容，請參考並優化，不要重複編造或刪除其核心重點。",
    "9. 只回傳 JSON 物件，不要加任何額外文字、markdown 標記或註解。"
  ].join("\n");
}

export function buildColloquialPrompt(before, after){
  return [
    "你是企業改善提案的撰寫助手。請把使用者的「改善前（問題）」與「改善後（對策）」描述，改寫成措辭正式、專業、莊重的一段文字，適合作為正式文件內容，供使用者呈報主管或複製貼入公司表格。",
    "",
    "改善前原始描述："+(before||"（未填）"),
    "改善後原始描述："+(after||"（未填）"),
    "",
    "規則：",
    "0. 必須使用台灣繁體中文，嚴禁出現任何簡體中文字形（例如：写→寫、车→車、机→機、对→對、来→來）。輸出前請逐字檢查。",
    "1. 使用正式、專業的中文措辭，語氣莊重且適合長官閱讀，避免過於口語、隨興或情緒化用語。",
    "2. 將描述分成數個編號列點，前面加上「1. 2. 3. …」，每個列點是一句完整的句子。",
    "3. 一句話寫完（後方有句號「。」）就跳行，再開始下一個列點，讓排版整齊，不要全部連成一大段。",
    "4. 不要使用「●」「-」等其他符號。",
    "5. 改善前：以正式語句說明問題現況、成因與影響。",
    "6. 改善後：以正式語句說明對策內容與執行方式。",
    "7. 全部繁體中文，各 100–150 字內。",
    "",
    "只回傳 JSON 物件：",
    "{",
    '  "before_conv": "改善前正式描述",',
    '  "after_conv": "改善後正式描述"',
    "}"
  ].join("\n");
}

export function buildVisionPrompt(){
  return [
    "你是一位工廠安全與改善顧問。請觀察使用者提供的「改善前」與「改善後」照片（會依序標示 before/after），分析內容後產出描述。",
    "",
    "規則：",
    "0. 必須使用台灣繁體中文，嚴禁出現任何簡體中文字形（例如：写→寫、车→車、机→機、对→對、来→來）。輸出前請逐字檢查。",
    "1. 改善前（before）：拆成 3 個「標題：內容」列點（例如：具體現象／根本成因／潛在風險），每點一行、開頭加「●」。",
    "2. 改善後（after）：拆成 3 個「標題：內容」列點（例如：具體對策／執行重點／預期效果），每點一行、開頭加「●」。",
    "3. 重點詞彙用「**」包起來（如 **滑倒**）。",
    "4. before 與 after 各 100 字內。",
    "",
    "只回傳 JSON：",
    '{ "before": "…", "after": "…" }'
  ].join("\n");
}

export function buildSlidePrompt(d){
  return [
    "你是改善提案簡報設計師。請依據以下內容，產出一頁式簡報的內容。",
    "",
    "改善主題："+(d.title||"（未填）"),
    "改善前："+(d.before||"（未填）"),
    "改善後："+(d.after||"（未填）"),
    "預期效益："+(d.benefits.filter(Boolean).join("、")||"（未填）"),
    "",
    "規則：重點簡潔、適合長官閱讀。必須使用台灣繁體中文，嚴禁出現任何簡體中文字形（例如：写→寫、车→車、机→機、对→對、来→來）。每項效益需包含一個百分比數字（如「減少停機 50%」），代表該面向的達成度（0-100），AI 自行判斷填入。輸出前請逐字檢查。",
    "回傳 chartType 欄位：若各效益為各自達成度的比較，用 \"bar\"（長條圖）；若各效益為整體成效的組成比例（數值加總接近 100%），用 \"pie\"（圓餅圖）。AI 自行判斷。",
    "",
    "只回傳 JSON：",
    '{ "slideTitle":"簡報標題（15 字內）", "keyPoints":["3 個重點，各 15 字內"], "benefits":["減少停機 50%","節省維修成本 30%","提升產能效率 20%"], "chartType":"bar", "conclusion":"結語一句（20 字內）" }'
  ].join("\n");
}
